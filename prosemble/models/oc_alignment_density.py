"""
One-class density of time series under monotone alignment (OCAlignmentDensity).

A series :math:`x \\in \\mathbb{R}^{T \\times C}` is generated by a prototype
series :math:`w_k \\in \\mathbb{R}^{L \\times C}`, a monotone alignment and
Gaussian noise:

.. math::

    p(x) = \\sum_k \\pi_k \\sum_{a} \\frac{\\tau(a)}{Z_\\tau}
           \\prod_{t=1}^{T} \\mathcal{N}(x_t;\\, w_{k, a_t},\\, \\Sigma_{k, a_t}),

where the alignment starts at :math:`a_1 = 1`, ends at :math:`a_T = L`
and moves by :math:`a_t - a_{t-1} \\in \\{0, 1, 2\\}` with probabilities
:math:`\\tau = (\\tau_0, \\tau_1, \\tau_2)`, and :math:`Z_\\tau` normalises
the alignment probabilities over the alignments that end at :math:`L`.
Every :math:`x_t` is emitted exactly once from a normalised Gaussian, so
:math:`p` is a normalised density on :math:`\\mathbb{R}^{T \\times C}`, and
:math:`\\log p(x)` is a forward recursion like soft-DTW's.

The model is fitted by expectation-maximisation from soft-DTW medoids of
the training series: the alignment posteriors are gradients of
:math:`\\log p` with respect to the log emissions, and the prototypes,
variances and mixture weights have closed-form updates. The variances are
per prototype position and channel, shrunk towards the shared variance of
each channel with a strength chosen by empirical Bayes, or one full
covariance over the channels.
"""

import math
from functools import partial

import jax
import jax.numpy as jnp
import numpy as np
import optax
from jax.scipy.special import gammaln, logsumexp

from prosemble.core.quantization import QuantizationMixin
from prosemble.core.serialization import SerializationMixin
from prosemble.core.soft_dtw import soft_dtw, soft_dtw_matrix

_NEG = -1e30
_COVARIANCES = ('position', 'shared')


# ----------------------------------------------------------------------
# Alignment likelihood
# ----------------------------------------------------------------------

def _shift(a, s):
    """``a[..., j - s]``, with -inf where ``j < s``."""
    if s >= a.shape[-1]:
        return jnp.full(a.shape, _NEG, a.dtype)
    pad = jnp.full(a.shape[:-1] + (s,), _NEG, a.dtype)
    return jnp.concatenate([pad, a[..., :-s]], axis=-1)


def _forward(log_e, log_tau):
    """Log of the sum over alignments ending at L of tau(a) prod_t exp(log_e[t, a_t]).

    ``log_e`` has shape (..., T, L); the result has shape (...).
    """
    L = log_e.shape[-1]
    init = jnp.full(log_e.shape[:-2] + (L,), _NEG, log_e.dtype).at[..., 0].set(log_e[..., 0, 0])

    def step(alpha, e):
        prev = jnp.stack([alpha + log_tau[0], _shift(alpha, 1) + log_tau[1],
                          _shift(alpha, 2) + log_tau[2]], axis=0)
        return e + logsumexp(prev, axis=0), None

    alpha, _ = jax.lax.scan(step, init, jnp.moveaxis(log_e[..., 1:, :], -2, 0))
    return alpha[..., L - 1]


def _log_z(T, L, log_tau):
    """Log of the total probability of the alignments of T steps that end at L."""
    return _forward(jnp.zeros((T, L)), log_tau)


def _log_emission(X, W, cov, shared):
    """log N(x_t; w_kl, Sigma) for X (n, T, C) and W (K, L, C): shape (n, K, T, L)."""
    C = X.shape[-1]
    if shared:
        P = jnp.linalg.inv(cov)
        logdet = jnp.linalg.slogdet(cov)[1]
        quad = (jnp.einsum('ntc,cd,ntd->nt', X, P, X)[:, None, :, None]
                - 2 * jnp.einsum('ntc,cd,kld->nktl', X, P, W)
                + jnp.einsum('klc,cd,kld->kl', W, P, W)[None, :, None, :])
    else:
        inv = 1.0 / cov
        logdet = jnp.sum(jnp.log(cov), -1)[None, :, None, :]
        quad = (jnp.einsum('ntc,klc->nktl', X ** 2, inv)
                - 2 * jnp.einsum('ntc,klc->nktl', X, W * inv)
                + jnp.sum(W ** 2 * inv, -1)[None, :, None, :])
    return -0.5 * (quad + logdet + C * math.log(2 * math.pi))


def _log_density(X, W, cov, log_pi, log_tau, shared):
    T, L = X.shape[1], W.shape[1]
    F = _forward(_log_emission(X, W, cov, shared), log_tau) - _log_z(T, L, log_tau)
    return logsumexp(log_pi[None] + F, axis=1)


_log_density_jit = jax.jit(_log_density, static_argnums=(5,))


def _expectations(X, W, cov, log_pi, log_tau, shared):
    """Sufficient statistics of one batch for EM."""
    T, L = X.shape[1], W.shape[1]

    def total(log_e, lpi, ltau):
        return jnp.sum(logsumexp(lpi[None] + _forward(log_e, ltau), axis=1))

    log_e = _log_emission(X, W, cov, shared)
    ll, (gamma, resp, counts) = jax.value_and_grad(total, argnums=(0, 1, 2))(log_e, log_pi, log_tau)
    S2 = (jnp.einsum('nktl,ntc,ntd->cd', gamma, X, X) if shared
          else jnp.einsum('nktl,ntc->klc', gamma, X ** 2))
    return dict(ll=ll - X.shape[0] * _log_z(T, L, log_tau), N=gamma.sum(axis=(0, 2)),
                S1=jnp.einsum('nktl,ntc->klc', gamma, X), S2=S2, resp=resp, counts=counts)


_expectations_jit = jax.jit(_expectations, static_argnums=(5,))


def _tau_objective(theta, counts, n, T, L):
    """Negative log-likelihood of the step probabilities: -(sum_d c_d log tau_d - n log Z(tau))."""
    log_tau = jax.nn.log_softmax(theta)
    return -(jnp.sum(counts * log_tau) - n * _log_z(T, L, log_tau))


@partial(jax.jit, static_argnums=(2, 3))
def _update_tau(counts, n, T, L, log_tau):
    """Maximise sum_d c_d log tau_d - n log Z(tau) over the simplex (100 Adam steps)."""
    opt = optax.adam(0.05)

    def body(_, carry):
        theta, state = carry
        updates, state = opt.update(jax.grad(_tau_objective)(theta, counts, n, T, L), state)
        return optax.apply_updates(theta, updates), state

    theta, _ = jax.lax.fori_loop(0, 100, body, (log_tau, opt.init(log_tau)))
    return jax.nn.log_softmax(theta)


def _eb_strength(resid, N, shared_var):
    """Prior strength of the per-position variances, by empirical Bayes.

    Each variance has an inverse-gamma prior with shape kappa/2 and scale
    kappa * s_c / 2 (mean about the shared variance s_c). With the variance
    integrated out, a position with occupancy N and residual sum R has the
    marginal likelihood
    a log b - lnG(a) + lnG(a + N/2) - (a + N/2) log(b + R/2) + const,
    a = kappa/2, b = kappa s_c/2; kappa_c maximises its sum over positions.
    """
    grid = jnp.logspace(-1, 4, 61)
    k = grid[:, None, None, None]
    R = jnp.maximum(resid, 0.0)[None]
    a, b = k / 2, k * shared_var[None, None, None] / 2
    half = N[None, ..., None] / 2
    ml = (a * jnp.log(b) - gammaln(a) + gammaln(a + half) - (a + half) * jnp.log(b + R / 2)).sum((1, 2))
    return grid[jnp.argmax(ml, axis=0)]


def _em(X, W, shared, n_iter, tol, batch):
    """EM for the alignment mixture, from prototypes ``W``."""
    n, T, C = X.shape
    K, L = W.shape[:2]
    var0 = jnp.var(X, axis=(0, 1))
    base = 1e-2 * jnp.mean(var0)
    cov = jnp.diag(0.25 * var0 + base) if shared else jnp.broadcast_to(0.25 * var0 + base, (K, L, C))
    log_pi = jnp.full(K, -math.log(K), jnp.float32)
    log_tau = jnp.log(jnp.array([0.25, 0.5, 0.25], jnp.float32))
    history = []
    for it in range(n_iter):
        acc = None
        for i in range(0, n, batch):
            s = _expectations_jit(X[i:i + batch], W, cov, log_pi, log_tau, shared)
            acc = s if acc is None else {key: acc[key] + s[key] for key in acc}
        history.append(float(acc['ll']) / n)
        N = acc['N']
        # A position that no series reaches keeps its prototype value.
        W = (acc['S1'] + 1e-3 * W) / (N[..., None] + 1e-3)
        total = jnp.sum(N)
        if shared:
            S1 = acc['S1']
            scatter = (acc['S2'] - jnp.einsum('klc,kld->cd', S1, W) - jnp.einsum('klc,kld->cd', W, S1)
                       + jnp.einsum('kl,klc,kld->cd', N, W, W))
            k0 = C + 2.0
            cov = (scatter + k0 * base * jnp.eye(C)) / (total + k0)
        else:
            resid = acc['S2'] - 2 * W * acc['S1'] + N[..., None] * W ** 2
            shared_var = (jnp.maximum(resid, 0).sum((0, 1)) + (C + 2.0) * base) / (total + C + 2.0)
            kappa = _eb_strength(resid, N, shared_var)
            cov = (jnp.maximum(resid, 0.0) + kappa * shared_var[None, None]) / (N[..., None] + kappa + 2.0)
        log_pi = jnp.log(jnp.maximum(acc['resp'], 1e-6) / n)
        log_tau = _update_tau(acc['counts'], jnp.float32(n), T, L, log_tau)
        if it > 2 and abs(history[-1] - history[-2]) < tol * abs(history[-2]):
            break
    return dict(W=W, cov=cov, log_pi=log_pi, log_tau=log_tau, history=history)


def kmedoids(D, k, rng, n_iter=20):
    """Indices of ``k`` medoids of a dissimilarity matrix ``D``.

    Seeds are chosen as in k-means++ from the dissimilarities; assignment to
    the nearest medoid and the choice of the member with the smallest total
    dissimilarity to its cluster then alternate until the medoids stop changing.
    """
    n = D.shape[0]
    medoids = [int(rng.integers(n))]
    for _ in range(k - 1):
        nearest = D[:, medoids].min(axis=1)
        total = nearest.sum()
        medoids.append(int(rng.choice(n, p=nearest / total)) if total > 0 else int(rng.integers(n)))
    medoids = np.array(medoids)
    for _ in range(n_iter):
        assign = D[:, medoids].argmin(axis=1)
        new = medoids.copy()
        for j in range(k):
            members = np.flatnonzero(assign == j)
            if members.size:
                new[j] = members[D[np.ix_(members, members)].sum(axis=1).argmin()]
        if np.array_equal(new, medoids):
            break
        medoids = new
    return medoids


# ----------------------------------------------------------------------
# Model
# ----------------------------------------------------------------------

class OCAlignmentDensity(SerializationMixin, QuantizationMixin):
    """One-class density model of time series under monotone alignment.

    Fitted to normal series only. :meth:`score_samples` is the log density
    of a series under the model; :meth:`decision_function` turns it into a
    score in (0, 1) with the boundary at 0.5, placed so that the fraction
    ``nu`` of the training series falls outside.

    Parameters
    ----------
    n_channels : int
        Number of channels C. Rows of ``X`` hold T x C values, time-major
        (all channels of the first time point, then the second, ...).
        Arrays of shape (n, T, C) are accepted as well.
    n_prototypes : int
        Number of prototype series (at most the number of training series).
        Default: 3.
    covariance : {'position', 'shared'}
        'position' (default): one variance per prototype position and
        channel, shrunk towards the shared variance of the channel with a
        strength chosen by empirical Bayes. 'shared': one full covariance
        over the channels for all prototypes and positions.
    nu : float
        Fraction of the training series to place outside the boundary of
        :meth:`decision_function`. Default: 0.05.
    max_iter : int
        Maximum number of EM iterations. Default: 50.
    tol : float
        Relative change of the mean log-likelihood that stops EM. Default: 1e-5.
    gamma : float
        Smoothing of the soft-DTW divergence used to find the medoids that
        start the prototypes. Default: 1.0.
    batch_bytes : float
        Approximate memory per batch of series in an EM step and in the
        medoid search. Default: 2e8.
    random_seed : int
        Seed of the medoid search. Default: 0.

    Attributes
    ----------
    prototypes_ : array of shape (K, T, C)
        The K prototype series (in standardised channel units).
    covariances_ : array
        (K, T, C) variances, or a (C, C) covariance for
        ``covariance='shared'``.
    log_weights_ : array of shape (K,)
        Log mixture weights :math:`\\log \\pi_k`.
    step_probabilities_ : array of shape (3,)
        Probabilities of the alignment steps 0, 1 and 2.
    threshold_ : float
        Log density at the boundary of :meth:`decision_function`.
    channel_mean_, channel_scale_ : arrays of shape (C,)
        Channel standardisation learned from the training series.
    n_iter_ : int
        Number of EM iterations run.
    loss_history_ : array
        Negative mean log-likelihood of the training series per iteration.

    Notes
    -----
    An EM step costs time proportional to the number of training series
    times ``n_prototypes`` times :math:`T^2`.

    References
    ----------
    .. [1] Cuturi, M., & Blondel, M. (2017). Soft-DTW: a Differentiable Loss
           Function for Time-Series. Proceedings of the 34th International
           Conference on Machine Learning, PMLR 70, 894-903.
    .. [2] Rabiner, L. R. (1989). A Tutorial on Hidden Markov Models and
           Selected Applications in Speech Recognition. Proceedings of the
           IEEE, 77(2), 257-286.
    .. [3] Kaufman, L., & Rousseeuw, P. J. (1990). Finding Groups in Data:
           An Introduction to Cluster Analysis. Wiley.
    """

    _fitted_names = ('prototypes_', 'covariances_', 'log_weights_', 'step_probabilities_',
                     'channel_mean_', 'channel_scale_')

    def __init__(self, n_channels=1, n_prototypes=3, covariance='position', nu=0.05,
                 max_iter=50, tol=1e-5, gamma=1.0, batch_bytes=2e8, random_seed=0):
        if covariance not in _COVARIANCES:
            raise ValueError(f"covariance must be 'position' or 'shared', got {covariance!r}")
        if not 0 < nu < 1:
            raise ValueError(f'nu must be in (0, 1), got {nu}')
        if int(n_prototypes) < 1:
            raise ValueError(f'n_prototypes must be at least 1, got {n_prototypes}')
        if int(n_channels) < 1:
            raise ValueError(f'n_channels must be at least 1, got {n_channels}')
        self.n_channels = int(n_channels)
        self.n_prototypes = int(n_prototypes)
        self.covariance = covariance
        self.nu = float(nu)
        self.max_iter = int(max_iter)
        self.tol = float(tol)
        self.gamma = float(gamma)
        self.batch_bytes = float(batch_bytes)
        self.random_seed = int(random_seed)
        self._quantized_dtype = None
        self.prototypes_ = None

    # -- data ----------------------------------------------------------

    def _series(self, X):
        X = np.asarray(X, dtype=np.float32)
        if X.ndim == 3:
            if X.shape[2] != self.n_channels:
                raise ValueError(f'expected {self.n_channels} channels, got {X.shape[2]}')
            return X
        if X.ndim != 2 or X.shape[1] % self.n_channels:
            raise ValueError(f'rows of X must hold T x {self.n_channels} values')
        return X.reshape(X.shape[0], -1, self.n_channels)

    def _standardised(self, X):
        return jnp.asarray((self._series(X) - self.channel_mean_) / self.channel_scale_)

    def _batch(self, n_components, T, L):
        return int(max(1, self.batch_bytes // (32.0 * n_components * T * L)))

    # -- fitting -------------------------------------------------------

    def _medoids(self, X, k, rng):
        """``k`` medoids of ``X`` under the soft-DTW divergence.

        A training set of more than 200 series is subsampled first, as in
        CLARA [3]_, and the divergences are computed in blocks of
        ``batch_bytes``.
        """
        if k == len(X):
            return X
        if len(X) > 200:
            X = X[rng.choice(len(X), 200, replace=False)]
        A = jnp.asarray(X)
        n, T, C = A.shape
        pairs = max(1, int(self.batch_bytes // (4.0 * T * T * (C + 3))))
        cols = min(n, pairs)
        rows = max(1, pairs // cols)
        own = np.concatenate([np.asarray(jax.vmap(lambda s: soft_dtw(s, s, self.gamma))(A[i:i + pairs]))
                              for i in range(0, n, pairs)])
        cross = np.concatenate([
            np.concatenate([np.asarray(soft_dtw_matrix(A[i:i + rows], A[j:j + cols], self.gamma))
                            for j in range(0, n, cols)], axis=1)
            for i in range(0, n, rows)])
        D = np.maximum(cross - 0.5 * own[:, None] - 0.5 * own[None, :], 0.0)
        return X[kmedoids(D, k, rng)]

    def fit(self, X, y=None):
        """Fit the density to normal series.

        Parameters
        ----------
        X : array-like of shape (n_series, T * n_channels) or (n_series, T, n_channels)
            Normal series only.
        y : ignored

        Returns
        -------
        self
        """
        series = self._series(X)
        n, T, C = series.shape
        if n < 2:
            raise ValueError('OCAlignmentDensity needs at least two training series')
        self.channel_mean_ = series.mean(axis=(0, 1))
        scale = series.std(axis=(0, 1))
        self.channel_scale_ = np.where(scale > 0, scale, 1.0).astype(np.float32)
        Z = (series - self.channel_mean_) / self.channel_scale_
        rng = np.random.default_rng(self.random_seed)
        k = min(self.n_prototypes, n)
        W = jnp.asarray(self._medoids(Z, k, rng))
        fit = _em(jnp.asarray(Z), W, self.covariance == 'shared', self.max_iter, self.tol,
                  self._batch(k, T, T))
        self.prototypes_ = fit['W']
        self.covariances_ = fit['cov']
        self.log_weights_ = fit['log_pi']
        self.step_probabilities_ = jnp.exp(fit['log_tau'])
        self.n_iter_ = len(fit['history'])
        self.loss_history_ = np.asarray([-v for v in fit['history']])
        self.threshold_ = float(np.quantile(self._score(jnp.asarray(Z)), self.nu))
        return self

    # -- prediction ----------------------------------------------------

    def _check_fitted(self):
        if self.prototypes_ is None:
            raise ValueError('OCAlignmentDensity is not fitted yet; call fit first')

    def _score(self, Z):
        W = jnp.asarray(self.prototypes_, jnp.float32)
        cov = jnp.asarray(self.covariances_, jnp.float32)
        log_pi = jnp.asarray(self.log_weights_, jnp.float32)
        log_tau = jnp.log(jnp.asarray(self.step_probabilities_, jnp.float32))
        batch = self._batch(W.shape[0], Z.shape[1], W.shape[1])
        return np.concatenate([np.asarray(_log_density_jit(
            Z[i:i + batch], W, cov, log_pi, log_tau, self.covariance == 'shared'))
            for i in range(0, len(Z), batch)])

    def score_samples(self, X):
        """Log density of each series under the model (channels standardised).

        Parameters
        ----------
        X : array-like of shape (n_series, T * n_channels) or (n_series, T, n_channels)

        Returns
        -------
        scores : array of shape (n_series,)
            Larger is more normal.
        """
        self._check_fitted()
        return jnp.asarray(self._score(self._standardised(X)))

    def decision_function(self, X):
        """Normality in (0, 1), with the decision boundary at 0.5.

        The score is :math:`p(x) / (p(x) + c)`, where :math:`c` is the density
        level below which the fraction ``nu`` of the training series falls.
        """
        return jax.nn.sigmoid(self.score_samples(X) - self.threshold_)

    def predict(self, X):
        """1 for a normal series, -1 for an anomalous one."""
        return jnp.where(self.decision_function(X) >= 0.5, 1, -1)

    # -- serialisation -------------------------------------------------

    def _get_hyperparams(self):
        return dict(n_channels=self.n_channels, n_prototypes=self.n_prototypes,
                    covariance=self.covariance, nu=self.nu, max_iter=self.max_iter,
                    tol=self.tol, gamma=self.gamma, batch_bytes=self.batch_bytes,
                    random_seed=self.random_seed)

    def _get_fitted_arrays(self):
        return {name: np.asarray(getattr(self, name)) for name in self._fitted_names}

    def _set_fitted_arrays(self, arrays):
        for name in self._fitted_names:
            value = np.asarray(arrays[name])
            setattr(self, name, value if name in ('channel_mean_', 'channel_scale_') else jnp.asarray(value))

    def _get_save_metadata(self):
        return dict(threshold_=self.threshold_)

    def _restore_metadata(self, metadata):
        self.threshold_ = float(metadata['threshold_'])

    def _get_quantizable_attrs(self):
        return ['prototypes_']
